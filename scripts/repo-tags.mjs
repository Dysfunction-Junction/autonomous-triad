#!/usr/bin/env node
// Tags: tooling, verification, protocol-contract
// Links: docs/TAG_VOCABULARY.md, docs/REPO_TAGS.md, .github/workflows/ci.yml
// Queries: "how is the tag index generated", "what does the audit reject", "why is a link reported missing"

/**
 * Build the repository tag index from per-file 3-line headers.
 *
 * Every tracked file may open with a header block like:
 *
 *   # Tags: advisor, failover
 *   # Links: triad/advisors.json, docs/ARCHITECTURE.md
 *   # Queries: "which advisor handles this tier", "why was an advisor skipped"
 *
 * The comment marker is free (`#`, `//`, `--`, `/*`, `*`, `<!--`), and Markdown
 * files may use `**Tags:** value` instead. This script reads the headers, writes
 * `REPO_TAGS.md` plus one page per tag under `tags/`, and reports how much of the
 * tree is still untagged.
 *
 * Ported from sovereign-exocortex/scripts/repo-tags.mjs. That repo vendors this
 * tree at packages/triad/, so the two indexes describe the same Python files; the
 * vocabulary does not carry over, because the host repo is a TypeScript product.
 *
 * Usage:
 *   node scripts/repo-tags.mjs                 # write docs/REPO_TAGS.md + docs/tags/
 *   node scripts/repo-tags.mjs --out <dir>     # write somewhere else (dry-run)
 *   node scripts/repo-tags.mjs --check         # exit 1 if the committed index is stale
 *   node scripts/repo-tags.mjs --list          # print the parsed headers, write nothing
 *   node scripts/repo-tags.mjs --audit         # lint headers against the vocabulary
 */

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const argv = process.argv.slice(2);
const flag = (name) => argv.includes(name);
const option = (name, fallback) => {
  const at = argv.indexOf(name);
  return at >= 0 && argv[at + 1] ? argv[at + 1] : fallback;
};

const OUT_DIR = option("--out", "docs");
const VOCAB_PATH = option("--vocab", "docs/TAG_VOCABULARY.md");
const CHECK = flag("--check");
const LIST = flag("--list");
const AUDIT = flag("--audit");
const HEADER_SCAN_LINES = 40;
const SKIP_DIRS = ["docs/tags/", "node_modules/", ".venv/"];
const SKIP_EXT = new Set([
  // No comment syntax: a header line would break the parse.
  ".json",
  // Not source: generated by uv, or a licence.
  ".lock",
  // Binary and image assets.
  ".png", ".jpg", ".jpeg", ".gif", ".webp", ".ico", ".pdf", ".zip", ".gz", ".tgz",
  ".woff", ".woff2", ".ttf", ".otf", ".mp3", ".mp4", ".wav", ".m4a", ".amr",
  ".so", ".dll", ".exe", ".bin", ".onnx", ".gguf", ".keystore", ".jks",
]);
// Hand-written or generated in this repo: neither can hold its own header without
// the file lying about itself. Excluding them keeps the coverage denominator honest,
// instead of printing a backlog row that no edit can ever clear.
const SKIP_PATH = /^(docs\/(REPO_TAGS\.md|TAG_VOCABULARY\.md|tags\/)|LICENSE)/;

// The marker is required: a comment/quote prefix in code, or `**Tags:**` in Markdown.
// A bare `tags:` line (YAML frontmatter, a fixture string, a legend paragraph) must not count.
const FIELD = /^\s*(?:\/\*+|<!--|@rem\s+|\/\/+|#+|--+|\*+|>)\s*\*{0,2}(tags|links|queries)\*{0,2}\s*:\s*(.*?)\s*$/i;

function normalizePath(p) {
  return p.replace(/\\/g, "/");
}

function git(...args) {
  return execFileSync("git", args, { encoding: "utf8" }).trim();
}

/** Split a header value into items. Quoted items win; otherwise split on commas. */
function splitList(raw) {
  // Markdown bold closes after the colon (`**Tags:** a, b`), so strip the marker
  // remnants plus an HTML comment tail before splitting.
  const value = raw
    .replace(/\s*-->\s*$/, "")
    .replace(/^\*+\s*/, "")
    .replace(/\s*\*+$/, "")
    .trim();
  if (!value) return [];
  const quoted = [...value.matchAll(/"([^"]+)"/g)].map((m) => m[1].trim()).filter(Boolean);
  if (quoted.length) return quoted;
  return value
    .split(",")
    .map((part) => part.trim().replace(/^[`'"]+|[`'"]+$/g, "").trim())
    .filter(Boolean);
}

/** Read the 3-line header out of one file, or null when it has none. */
function readHeader(path) {
  let text;
  try {
    text = readFileSync(path, "utf8");
  } catch {
    return null;
  }
  const lines = text.split(/\r?\n/, HEADER_SCAN_LINES);
  const header = { tags: [], links: [], queries: [] };
  for (const line of lines) {
    const match = FIELD.exec(line);
    if (!match) continue;
    const key = match[1].toLowerCase();
    for (const item of splitList(match[2])) header[key].push(item);
  }
  if (!header.tags.length && !header.links.length && !header.queries.length) return null;
  return header;
}

const slugify = (tag) =>
  tag.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "") || "untitled";

const areaOf = (path) => {
  const parts = path.split("/");
  if (parts.length === 1) return "(repo root)";
  const top = parts[0];
  // A file sitting directly in docs/ belongs to the root docs group, not to a
  // pseudo-area named after itself.
  if (top === "docs" && (parts.length === 2 || parts[1].includes("."))) return "docs (root)";
  if (top === "triad" || top === "skills") return `${top}/${parts[1]}`;
  return top;
};

// ---------------------------------------------------------------- collect

// `git ls-files` prints an unmerged path once per index stage (1/2/3) while a merge is
// in progress, so dedupe before it reaches the coverage denominator.
const tracked = [...new Set(git("ls-files", "-z").split("\0").filter(Boolean))];
const branch = (() => {
  try {
    return git("rev-parse", "--abbrev-ref", "HEAD");
  } catch {
    return "(detached)";
  }
})();
const commit = git("rev-parse", "--short", "HEAD");

const entries = [];
const untaggedByArea = new Map();
let considered = 0;
for (const path of tracked) {
  if (SKIP_DIRS.some((dir) => path.startsWith(dir))) continue;
  if (SKIP_PATH.test(path)) continue;
  // Dotfiles are read verbatim by tooling and by git; a header in them is noise.
  if (path.split("/").pop().startsWith(".")) continue;
  const dot = path.lastIndexOf(".");
  if (dot > 0 && SKIP_EXT.has(path.slice(dot).toLowerCase())) continue;
  considered++;
  const header = readHeader(path);
  if (header) entries.push({ path, ...header });
  else untaggedByArea.set(areaOf(path), (untaggedByArea.get(areaOf(path)) ?? 0) + 1);
}

entries.sort((a, b) => a.path.localeCompare(b.path));

const tagMap = new Map();
for (const entry of entries) {
  for (const tag of new Set(entry.tags)) {
    const slug = slugify(tag);
    if (!tagMap.has(slug)) tagMap.set(slug, { label: tag, files: [] });
    tagMap.get(slug).files.push({ path: entry.path, links: entry.links, queries: entry.queries });
  }
}
const tagSlugs = [...tagMap.keys()].sort();

// ---------------------------------------------------------------- render

const esc = (text) => text.replace(/\|/g, "\\|");
const cell = (items, fallback = "—") => (items.length ? items.map((i) => `\`${esc(i)}\``).join("<br>") : fallback);
const percent = (part, whole) => (whole ? ((part / whole) * 100).toFixed(1) : "0.0");

const total = considered;
const tagged = entries.length;

// ---------------------------------------------------------------- audit

// Header lint: the check a writer (agent or human) runs after adding tags.
// Errors mean the index would point somewhere that does not exist.
const trackSet = new Set(tracked);

/** The frozen vocabulary. A tag outside it is an error, so naming cannot drift per file. */
function loadVocabulary() {
  if (!existsSync(VOCAB_PATH)) return null;
  const tags = new Set();
  for (const line of readFileSync(VOCAB_PATH, "utf8").split(/\r?\n/)) {
    const match = /^\|\s*`([a-z0-9][a-z0-9-]*)`\s*\|/.exec(line);
    if (match) tags.add(match[1]);
  }
  return tags.size ? tags : null;
}

const headingSlug = (heading) =>
  heading.toLowerCase().replace(/[`*_]/g, "").replace(/[^\w\s-]/g, "").trim().replace(/\s+/g, "-");
const isDirLink = (link) => link.endsWith("/") && tracked.some((path) => path.startsWith(link));

function audit() {
  const errors = [];
  const warnings = [];
  const allSlugs = new Set(tagSlugs);
  const vocabulary = loadVocabulary();
  if (!vocabulary) warnings.push(`${VOCAB_PATH} not found or empty — tag names are unchecked`);
  const breadth = new Map();

  for (const entry of entries) {
    if (!entry.tags.length) errors.push(`${entry.path}: header has no Tags`);
    if (new Set(entry.tags).size !== entry.tags.length) warnings.push(`${entry.path}: duplicate tag`);
    if (entry.tags.length > 6) warnings.push(`${entry.path}: ${entry.tags.length} tags — 2 to 6 is the useful range`);
    for (const tag of entry.tags) {
      if (!allSlugs.has(slugify(tag))) errors.push(`${entry.path}: tag "${tag}" has no slug`);
      if (vocabulary && !vocabulary.has(tag)) {
        errors.push(`${entry.path}: tag "${tag}" is not in ${VOCAB_PATH}`);
      }
      breadth.set(tag, (breadth.get(tag) ?? 0) + 1);
    }
    for (const link of entry.links) {
      const [target, anchor] = link.split("#");
      const hit = trackSet.has(target) || isDirLink(target);
      if (!hit) {
        const guess = tracked.find((path) => path === target || path.endsWith(`/${target}`));
        errors.push(`${entry.path}: link "${link}" does not exist${guess ? ` — did you mean ${guess}?` : ""}`);
        continue;
      }
      if (!anchor) continue;
      const scope = target.endsWith("/") ? target : target;
      const candidates = tracked.filter((path) => (scope.endsWith("/") ? path.startsWith(scope) : path === scope));
      const found = candidates.some((path) => {
        const text = readFileSync(path, "utf8");
        for (const match of text.matchAll(/^#{1,6}\s+(.+)$/gm)) {
          if (headingSlug(match[1]) === headingSlug(anchor)) return true;
        }
        return false;
      });
      if (!found) warnings.push(`${entry.path}: link "${link}" — no heading "${anchor}" in ${target}`);
    }
  }

  for (const line of errors) console.error(`error: ${line}`);
  for (const line of warnings) console.error(`warn:  ${line}`);
  if (vocabulary && entries.length) {
    const ceiling = Math.floor(total * 0.15);
    for (const [tag, count] of [...breadth.entries()].sort((a, b) => b[1] - a[1])) {
      if (count > ceiling) {
        console.warn(`breadth: "${tag}" is on ${count} files (> ${ceiling}); it no longer discriminates`);
      }
    }
    const unused = [...vocabulary].filter((tag) => !breadth.has(tag));
    if (unused.length) console.log(`unused vocabulary: ${unused.join(", ")}`);
  }
  console.log(`audited ${entries.length} tagged file(s): ${errors.length} error(s), ${warnings.length} warning(s)`);
  process.exit(errors.length ? 1 : 0);
}

const index = [];
index.push("# Repository tag index");
index.push("");
index.push("> Generated view — do not edit. Regenerate with `node scripts/repo-tags.mjs`.");
index.push(`> Source: \`git ls-files\` · branch \`${branch}\` · commit \`${commit}\` · ${total} tracked files.`);
index.push(">");
index.push("> `Tags/Links/Queries` is the header written at the top of each file. This file is the map;");
index.push("> the headers are the body. Both move together in the same commit.");
index.push("");
index.push(`**Coverage:** ${tagged} / ${total} files carry a tag header (${percent(tagged, total)}%). ` +
  `${total - tagged} untagged.`);
index.push("");
index.push("## How to read this");
index.push("");
index.push("| Field | Meaning |");
index.push("| --- | --- |");
index.push("| Tags | coarse filter — `grep` this file for a tag to find its files |");
index.push("| Links | where to look next: the file that calls this one, a doc, a config |");
index.push("| Queries | the questions the file answers, in the words you would ask them |");
index.push("");
index.push("Per-tag pages live under [`tags/`](tags/). They are generated too.");
index.push("");
index.push("The vocabulary is frozen in [`TAG_VOCABULARY.md`](TAG_VOCABULARY.md). A tag outside it fails");
index.push("`--audit`. `sovereign-exocortex` vendors this tree at `packages/triad/`; headers written here");
index.push("flow downstream on the next `scripts/update-triad.ps1` sync, so tag here and never there.");
index.push("");

if (!tagged) {
  index.push("## Tagged files");
  index.push("");
  index.push("No file carries a tag header yet. Add one like:");
  index.push("");
  index.push("```text");
  index.push("# Tags: <topic>, <topic>");
  index.push("# Links: <file that calls this one>, <doc>");
  index.push('# Queries: "<question this file answers>", "<another>"');
  index.push("```");
  index.push("");
} else {
  index.push("## Tagged files");
  index.push("");
  index.push("| File | Tags | Links |");
  index.push("| --- | --- | --- |");
  for (const entry of entries) index.push(`| \`${esc(entry.path)}\` | ${cell(entry.tags)} | ${cell(entry.links)} |`);
  index.push("");
}

if (tagSlugs.length) {
  index.push("## Tags");
  index.push("");
  index.push("| Tag | Files | Page |");
  index.push("| --- | --- | --- |");
  for (const slug of tagSlugs) {
    const { label, files } = tagMap.get(slug);
    index.push(`| \`${esc(label)}\` | ${files.length} | [tags/${slug}.md](tags/${slug}.md) |`);
  }
  index.push("");
}

const backlog = [...untaggedByArea.entries()].sort((a, b) => b[1] - a[1]);
if (backlog.length) {
  index.push("## Backfill backlog");
  index.push("");
  index.push("Untagged files per area, largest first. Tag the areas you actually query.");
  index.push("");
  index.push("| Area | Untagged files |");
  index.push("| --- | --- |");
  for (const [area, count] of backlog) index.push(`| \`${esc(area)}\` | ${count} |`);
  index.push("");
}

const indexText = index.join("\n");

const pages = new Map();
for (const slug of tagSlugs) {
  const { label, files } = tagMap.get(slug);
  const lines = [];
  lines.push(`# Tag: \`${label}\``);
  lines.push("");
  lines.push(`[← index](../REPO_TAGS.md) · ${files.length} file${files.length === 1 ? "" : "s"}`);
  lines.push("");
  lines.push("| File | Links | Queries |");
  lines.push("| --- | --- | --- |");
  for (const file of files) {
    lines.push(`| \`${esc(file.path)}\` | ${cell(file.links)} | ${cell(file.queries)} |`);
  }
  lines.push("");
  pages.set(`tags/${slug}.md`, lines.join("\n"));
}

// ---------------------------------------------------------------- output

if (AUDIT) {
  audit();
} else if (LIST) {
  for (const entry of entries) {
    console.log(`${entry.path}\n  tags:    ${entry.tags.join(", ")}`);
    if (entry.links.length) console.log(`  links:   ${entry.links.join(", ")}`);
    if (entry.queries.length) console.log(`  queries: ${entry.queries.join(" | ")}`);
  }
  console.log(`\n${tagged} tagged / ${total} tracked · ${tagSlugs.length} distinct tags`);
  process.exit(0);
}

const pending = new Map([[join(OUT_DIR, "REPO_TAGS.md"), indexText]]);
for (const [rel, text] of pages) pending.set(join(OUT_DIR, rel), text);

if (CHECK) {
  let stale = 0;
  // Three things legitimately vary without the tag data changing: the provenance line
  // (it names the commit, so committing the index would always make it "stale"), the
  // coverage count and the backlog table (both move whenever any file is added), and
  // CRLF line endings from a core.autocrlf checkout. Compare around all of them, so a
  // routine merge of new files does not read as tag drift.
  const comparable = (text) => {
    const lines = text.replace(/\r\n/g, "\n").split("\n");
    const cut = lines.findIndex((line) => line.startsWith("## Backfill backlog"));
    return (cut >= 0 ? lines.slice(0, cut) : lines)
      .map((line) => {
        if (line.startsWith("> Source:")) return "> Source: <dynamic>";
        if (line.startsWith("**Coverage:**")) return "**Coverage:** <dynamic>";
        return line;
      })
      .join("\n")
      .replace(/\n+$/, "");
  };
  for (const [file, expected] of pending) {
    const actual = existsSync(file) ? readFileSync(file, "utf8") : null;
    if (actual === null || comparable(actual) !== comparable(expected)) {
      console.error(`stale: ${normalizePath(file)}`);
      stale++;
    }
  }
  const orphans = existsSync(join(OUT_DIR, "tags"))
    ? readdirSync(join(OUT_DIR, "tags")).filter((name) => name.endsWith(".md")).map((name) => `tags/${name}`)
        .filter((rel) => !pending.has(join(OUT_DIR, rel)))
    : [];
  for (const rel of orphans) {
    console.error(`orphan: ${normalizePath(join(OUT_DIR, rel))}`);
    stale++;
  }
  console.log(stale ? `tag index stale (${stale} file(s)); run node scripts/repo-tags.mjs` : "tag index up to date");
  process.exitCode = stale ? 1 : 0;
} else {
  mkdirSync(join(OUT_DIR, "tags"), { recursive: true });
  for (const [file, text] of pending) {
    mkdirSync(join(OUT_DIR, "tags"), { recursive: true });
    writeFileSync(file, text, "utf8");
  }
  // Drop pages for tags that no longer exist, so the index cannot rot.
  for (const name of readdirSync(join(OUT_DIR, "tags"))) {
    const rel = `tags/${name}`;
    if (name.endsWith(".md") && !pending.has(join(OUT_DIR, rel))) rmSync(join(OUT_DIR, rel));
  }
  console.log(`wrote ${normalizePath(join(OUT_DIR, "REPO_TAGS.md"))} + ${pages.size} tag page(s)`);
  console.log(`coverage: ${tagged}/${total} files (${percent(tagged, total)}%) · ${tagSlugs.length} tags · ` +
    `${backlog.length} area(s) with untagged files`);
  if (tagged < total) {
    console.log("next: tag the top areas in the backlog, then re-run");
  }
}
